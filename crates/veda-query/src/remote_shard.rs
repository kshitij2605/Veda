/// A [`ShardSearcher`] that proxies to a remote [`ShardSearchService`].
///
/// Holds a tonic client plus the target collection / shard_id. Registered
/// in a `DistributedQueryExecutor` for shards that live on OTHER nodes,
/// alongside `LocalShardSearcher`s for local shards.
///
/// Because the `ShardSearcher` trait is synchronous but tonic is async,
/// each call blocks on a dedicated current-thread runtime. This keeps the
/// existing fan-out (in `DistributedQueryExecutor`) unchanged. A future
/// async fan-out can call the client directly.
pub struct RemoteShardSearcher {
    collection: String,
    shard_id: u32,
    client: tokio::sync::Mutex<ShardSearchClient<tonic::transport::Channel>>,
    runtime: tokio::runtime::Handle,
}

impl RemoteShardSearcher {
    /// Build by dialling `endpoint` (e.g. `http://10.0.0.7:6343`).
    ///
    /// Must be called from within a Tokio runtime; the captured runtime
    /// handle is used to drive the (async) RPC from the synchronous
    /// `ShardSearcher` trait methods.
    pub async fn connect(
        collection: impl Into<String>,
        shard_id: u32,
        endpoint: impl Into<String>,
    ) -> Result<Self> {
        let ep = endpoint.into();
        let channel = tonic::transport::Endpoint::from_shared(ep.clone())
            .map_err(|e| VedaError::Query(format!("endpoint {ep}: {e}")))?
            .connect()
            .await
            .map_err(|e| VedaError::Query(format!("dial {ep}: {e}")))?;
        Ok(Self::from_channel(collection, shard_id, channel))
    }

    /// Build from a pre-existing channel (useful when pooling channels
    /// across many remote shards on the same node).
    pub fn from_channel(
        collection: impl Into<String>,
        shard_id: u32,
        channel: tonic::transport::Channel,
    ) -> Self {
        Self {
            collection: collection.into(),
            shard_id,
            client: tokio::sync::Mutex::new(ShardSearchClient::new(channel)),
            runtime: tokio::runtime::Handle::current(),
        }
    }

    async fn search_async(
        &self,
        request: &VectorSearchRequest,
    ) -> Result<(Vec<ScoredRecord>, SearchTimings)> {
        let query = bincode::serialize(request)
            .map_err(|e| VedaError::Query(format!("encode VectorSearchRequest: {e}")))?;
        let rpc = SearchShardRequest {
            collection: self.collection.clone(),
            shard_id: self.shard_id,
            query,
            k: request.k as u32,
        };
        let mut client = self.client.lock().await;
        let reply = client
            .search_shard(Request::new(rpc))
            .await
            .map_err(|e| VedaError::Query(format!("remote search_shard: {e}")))?
            .into_inner();
        drop(client);

        let mut results = Vec::with_capacity(reply.results.len());
        for m in reply.results {
            results.push(ScoredRecord {
                id: uuid_from_bytes_q(&m.id)?,
                segment_id: uuid_from_bytes_q(&m.segment_id)?,
                doc_id: m.doc_id,
                distance: m.distance,
            });
        }
        let timings = SearchTimings {
            filter_ms: reply.filter_ms,
            ann_search_ms: reply.ann_search_ms,
            scoring_ms: reply.scoring_ms,
        };
        Ok((results, timings))
    }
}

fn uuid_from_bytes_q(b: &[u8]) -> Result<Uuid> {
    let arr: [u8; 16] = b
        .try_into()
        .map_err(|_| VedaError::Query("uuid must be 16 bytes".into()))?;
    Ok(Uuid::from_bytes(arr))
}

impl ShardSearcher for RemoteShardSearcher {
    fn search_shard(
        &self,
        _shard_id: u32,
        request: &VectorSearchRequest,
    ) -> Result<(Vec<ScoredRecord>, SearchTimings)> {
        // Bridge sync trait → async client on the captured runtime.
        tokio::task::block_in_place(|| self.runtime.block_on(self.search_async(request)))
    }

    // Sparse and multi-vector search are not supported over the remote
    // transport in Phase 1 — return a clean error (never panic). The
    // proto carries only the single-vector `VectorSearchRequest` shape.
    fn search_shard_sparse(
        &self,
        _shard_id: u32,
        _request: &crate::search::SparseSearchRequest,
    ) -> Result<(Vec<ScoredRecord>, SearchTimings)> {
        Err(VedaError::Query(
            "sparse search not supported over remote shard searcher (v1)".into(),
        ))
    }

    fn search_shard_multi_vector(
        &self,
        _shard_id: u32,
        _request: &crate::search::MultiVectorSearchRequest,
    ) -> Result<(Vec<ScoredRecord>, SearchTimings)> {
        Err(VedaError::Query(
            "multi-vector search not supported over remote shard searcher (v1)".into(),
        ))
    }
}


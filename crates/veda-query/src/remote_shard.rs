/// Pull full `Record`s for `ids` from a remote node via `FetchRecords`.
///
/// The gateway's fetch phase (`populate_hit_fields`) calls this when a
/// hit's owning shard is remote. Returns the records that the remote node
/// found (ids it could not resolve are silently skipped, matching the
/// local `lookup_record` returning `None`).
pub async fn fetch_records_remote(
    channel: tonic::transport::Channel,
    collection: &str,
    ids: &[Uuid],
) -> Result<Vec<Record>> {
    let mut client = ShardSearchClient::new(channel);
    let rpc = FetchRecordsRequest {
        collection: collection.to_owned(),
        ids: ids.iter().map(uuid_to_bytes).collect(),
    };
    let reply: FetchRecordsReply = client
        .fetch_records(Request::new(rpc))
        .await
        .map_err(|e| VedaError::Query(format!("remote fetch_records: {e}")))?
        .into_inner();

    let mut out = Vec::with_capacity(reply.records.len());
    for enc in reply.records {
        let rec: Record = bincode::deserialize(&enc)
            .map_err(|e| VedaError::Query(format!("decode Record: {e}")))?;
        out.push(rec);
    }
    Ok(out)
}

/// Convenience: build a `SegmentManager`-backed local searcher and wrap
/// it in an `Arc` for hosting in [`ShardSearchService`]. The caller
/// builds indexes first if needed.
pub fn host_segment_manager(sm: SegmentManager) -> Arc<LocalShardSearcher> {
    Arc::new(LocalShardSearcher::new(sm))
}

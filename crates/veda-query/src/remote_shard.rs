//! gRPC transport for multi-node distributed search (Phase D).
//!
//! Veda's `DistributedQueryExecutor` fans a query out to a set of
//! [`ShardSearcher`]s. Until now the only impl was
//! [`crate::local_shard::LocalShardSearcher`], which searches
//! in-process `SegmentManager`s. This module ships the remote leg:
//!
//! - [`ShardSearchService`] — a tonic service that hosts one or more
//!   local shard searchers (keyed by `(collection, shard_id)`) and
//!   exposes them over gRPC. Backed by the same
//!   `Arc<LocalShardSearcher>` handles the gateway already holds.
//! - [`RemoteShardSearcher`] — a [`ShardSearcher`] impl that proxies
//!   `search_shard` to a remote `ShardSearchService` over gRPC. The
//!   `DistributedQueryExecutor` can register a mix of local and remote
//!   searchers and merge their results identically (the trait hides
//!   the transport).
//! - [`fetch_records_remote`] — the fetch-phase client: pull full
//!   `Record`s for a set of ids from a remote node via `FetchRecords`.
//!
//! Wire format mirrors veda-log's tonic transport: the query rides as
//! an opaque `bytes` (bincode of `VectorSearchRequest`); only the
//! lightweight `ScoredRecord` (ids + score, NO vectors / documents)
//! crosses the wire on `SearchShard`. Full records are fetched
//! separately, on demand, for the final top-k.


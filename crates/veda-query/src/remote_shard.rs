/// Hosts local shard searchers and serves them over gRPC.
///
/// One service instance can host any number of `(collection, shard_id)`
/// shards. Constructed from the same `Arc<LocalShardSearcher>` handles
/// the node already uses for in-process search.
pub struct ShardSearchService {
    shards: HashMap<ShardKey, Arc<LocalShardSearcher>>,
}

impl Default for ShardSearchService {
    fn default() -> Self {
        Self::new()
    }
}

impl ShardSearchService {
    pub fn new() -> Self {
        Self {
            shards: HashMap::new(),
        }
    }

    /// Register a shard's local searcher under `(collection, shard_id)`.
    pub fn register(
        &mut self,
        collection: impl Into<String>,
        shard_id: u32,
        searcher: Arc<LocalShardSearcher>,
    ) {
        self.shards.insert((collection.into(), shard_id), searcher);
    }

    fn route(&self, collection: &str, shard_id: u32) -> std::result::Result<&Arc<LocalShardSearcher>, Status> {
        self.shards
            .get(&(collection.to_owned(), shard_id))
            .ok_or_else(|| {
                Status::not_found(format!("shard {collection}:{shard_id} not hosted"))
            })
    }
}

#[tonic::async_trait]
impl ShardSearch for ShardSearchService {
    async fn search_shard(
        &self,
        req: Request<SearchShardRequest>,
    ) -> std::result::Result<Response<SearchShardReply>, Status> {
        let req = req.into_inner();
        let searcher = self.route(&req.collection, req.shard_id)?;
        let mut request: VectorSearchRequest = bincode::deserialize(&req.query)
            .map_err(|e| Status::invalid_argument(format!("decode VectorSearchRequest: {e}")))?;
        // Honour the wire-level k (the request envelope carries it
        // explicitly; keep the embedded request consistent).
        request.k = req.k as usize;

        let (results, timings) = searcher
            .search_shard(req.shard_id, &request)
            .map_err(|e| Status::internal(format!("search_shard: {e}")))?;

        let total_candidates = results.len() as u32;
        let msgs: Vec<ScoredRecordMsg> = results
            .into_iter()
            .map(|r| ScoredRecordMsg {
                id: uuid_to_bytes(&r.id),
                segment_id: uuid_to_bytes(&r.segment_id),
                doc_id: r.doc_id,
                distance: r.distance,
            })
            .collect();

        Ok(Response::new(SearchShardReply {
            results: msgs,
            total_candidates,
            filter_ms: timings.filter_ms,
            ann_search_ms: timings.ann_search_ms,
            scoring_ms: timings.scoring_ms,
        }))
    }

    async fn fetch_records(
        &self,
        req: Request<FetchRecordsRequest>,
    ) -> std::result::Result<Response<FetchRecordsReply>, Status> {
        let req = req.into_inner();
        // Records may live in any shard this node hosts for the
        // collection; search all of them for each id.
        let local_shards: Vec<&Arc<LocalShardSearcher>> = self
            .shards
            .iter()
            .filter(|((c, _), _)| c == &req.collection)
            .map(|(_, s)| s)
            .collect();

        let mut records: Vec<Vec<u8>> = Vec::with_capacity(req.ids.len());
        for id_bytes in &req.ids {
            let id = uuid_from_bytes(id_bytes)?;
            let mut found: Option<Record> = None;
            for s in &local_shards {
                if let Some(rec) = s.lookup_record(id) {
                    found = Some(rec);
                    break;
                }
            }
            if let Some(rec) = found {
                let enc = bincode::serialize(&rec)
                    .map_err(|e| Status::internal(format!("encode Record: {e}")))?;
                records.push(enc);
            }
        }

        Ok(Response::new(FetchRecordsReply { records }))
    }
}


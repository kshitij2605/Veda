/// Routing key: a shard belongs to a `(collection, shard_id)` pair.
type ShardKey = (String, u32);

fn uuid_to_bytes(id: &Uuid) -> Vec<u8> {
    id.as_bytes().to_vec()
}

fn uuid_from_bytes(b: &[u8]) -> std::result::Result<Uuid, Status> {
    let arr: [u8; 16] = b
        .try_into()
        .map_err(|_| Status::invalid_argument("uuid must be 16 bytes"))?;
    Ok(Uuid::from_bytes(arr))
}


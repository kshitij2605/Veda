//! Recall-qualified CAGRA-vs-HNSW benchmark on real GPU hardware.
//!
//! Latency without recall is meaningless for an ANN index: any index can be
//! made arbitrarily fast by returning worse answers. Every latency figure
//! here is therefore printed alongside the recall@10 it was measured at,
//! against exact brute-force ground truth over the same vectors.
//!
//! Requires the `gpu_cuvs` feature, a GPU, and the environment described in
//! `documentation/2026-08-15-gpu-cuvs-cagra-design.md` ("Build recipe").
//!
//! Run with:
//! `cargo test -p veda-index --features gpu_cuvs --test cagra_gpu_bench -- --ignored --nocapture --test-threads=1`
//!
//! `--test-threads=1` is not optional: the two cases would otherwise
//! contend for the same GPU and hold both corpora in host memory at once,
//! and the reported latencies would measure the contention rather than the
//! indexes.
#![cfg(feature = "gpu_cuvs")]

use std::collections::HashSet;
use std::io::Write;
use std::time::Instant;

use veda_core::types::DistanceMetric;
use veda_index::flat::FlatIndex;
use veda_index::gpu_cuvs::CagraIndex;
use veda_index::hnsw::HnswIndex;
use veda_index::traits::VectorIndex;

const DIM: usize = 128;
const K: usize = 10;
const QUERIES: usize = 200;
const WARMUP: usize = 20;
const SEED: u64 = 0x5EED_1234;
const CENTROID_SEED: u64 = 0xC0FF_EE01;

/// Same LCG as `tests/ann_benchmark.rs`, so both benchmarks describe the
/// same synthetic corpus and their numbers stay comparable.
struct Lcg {
    state: u64,
}

impl Lcg {
    fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    fn next_f32_signed(&mut self) -> f32 {
        self.state = self.state.wrapping_mul(6364136223846793005).wrapping_add(1);
        (((self.state >> 32) as u32 as f32) / (u32::MAX as f32)) * 2.0 - 1.0
    }
}

/// Number of clusters the corpus is drawn from, and the radius of each.
const CLUSTERS: usize = 1_000;
const CLUSTER_SIGMA: f32 = 0.10;

/// Generate a **clustered** corpus: `CLUSTERS` uniform centroids, each point
/// a small perturbation of one of them.
///
/// Uniform-random vectors are the wrong instrument for this measurement. In
/// 128 dimensions they are all nearly equidistant, so the "true" top-10 is
/// close to arbitrary and every graph index scores near chance — this
/// benchmark first ran on uniform data and produced recall@10 of 0.37
/// (CAGRA) and 0.51 (HNSW), which says nothing about either index.
///
/// This is not a novel observation, it is already recorded in
/// `documentation/scale-benchmark-results.md`: HNSW measured recall@10 =
/// 0.38 on a uniform-random 100K x 1024d corpus, and 1.0 on a real,
/// weakly-clustered one. Real embeddings are clustered; the intrinsic
/// dimensionality is far below the ambient dimension. A corpus with cluster
/// structure is the representative case, and it is the only one on which
/// "CAGRA vs HNSW at comparable recall" is a meaningful question.
fn generate(n: usize, dim: usize, seed: u64) -> Vec<Vec<f32>> {
    // Centroids come from a FIXED seed, never from `seed`. The corpus and
    // the query set are generated by separate calls; if each derived its own
    // centroids, the queries would sit in the gaps between the corpus's
    // clusters and have no well-defined neighbours — which is the very
    // problem this clustering is here to remove.
    let mut crng = Lcg::new(CENTROID_SEED);
    let centroids: Vec<Vec<f32>> = (0..CLUSTERS)
        .map(|_| (0..dim).map(|_| crng.next_f32_signed()).collect())
        .collect();
    let mut rng = Lcg::new(seed);
    (0..n)
        .map(|i| {
            let c = &centroids[i % CLUSTERS];
            (0..dim)
                .map(|d| c[d] + rng.next_f32_signed() * CLUSTER_SIGMA)
                .collect()
        })
        .collect()
}

/// Print a result line and flush it immediately.
///
/// Not cosmetic: this benchmark is run redirected to a log file, where
/// Rust's stdout is block-buffered rather than line-buffered. The 1M HNSW
/// build takes hours (`HnswIndex::build` inserts sequentially), so without
/// an explicit flush the 100k results would sit invisible in the buffer for
/// the whole run, and a crash would lose them entirely.
fn emit(line: String) {
    println!("{line}");
    let _ = std::io::stdout().flush();
}

fn recall_at_k(predicted: &[Vec<u32>], truth: &[Vec<u32>]) -> f64 {
    assert_eq!(predicted.len(), truth.len());
    let mut total = 0.0;
    for (pred, gt) in predicted.iter().zip(truth.iter()) {
        let gt_set: HashSet<u32> = gt.iter().take(K).copied().collect();
        let hits = pred.iter().take(K).filter(|id| gt_set.contains(id)).count();
        total += hits as f64 / gt_set.len().max(1) as f64;
    }
    total / predicted.len() as f64
}

/// Time `search` over the query set, returning (mean microseconds, results).
///
/// A warmup pass runs first and is discarded: the first GPU search pays
/// lazy CUDA context and workspace initialisation, which would otherwise be
/// charged to the mean and make CAGRA look worse than it is.
fn timed_search(index: &dyn VectorIndex, queries: &[Vec<f32>]) -> (f64, Vec<Vec<u32>>) {
    for q in queries.iter().take(WARMUP) {
        index.search(q, K).expect("warmup search");
    }

    let mut results = Vec::with_capacity(queries.len());
    let start = Instant::now();
    for q in queries {
        let hits = index.search(q, K).expect("search");
        results.push(hits.into_iter().map(|r| r.id).collect());
    }
    let mean_us = start.elapsed().as_secs_f64() * 1e6 / queries.len() as f64;
    (mean_us, results)
}

/// Build both indexes over the same `n` vectors and print one grep-able
/// line each. Ground truth is exact brute force via `FlatIndex`.
fn run_case(n: usize) {
    let vectors = generate(n, DIM, SEED);
    let queries = generate(QUERIES, DIM, SEED ^ 0xFFFF);
    let refs: Vec<&[f32]> = vectors.iter().map(|v| v.as_slice()).collect();

    // Exact ground truth.
    let mut flat = FlatIndex::new(DistanceMetric::Euclidean, DIM as u32);
    flat.build(&refs).expect("flat build");
    let truth: Vec<Vec<u32>> = queries
        .iter()
        .map(|q| {
            flat.search(q, K)
                .expect("exact search")
                .into_iter()
                .map(|r| r.id)
                .collect()
        })
        .collect();

    // CAGRA on the GPU.
    let mut cagra = CagraIndex::new(DistanceMetric::Euclidean, DIM as u32);
    let t = Instant::now();
    cagra.build(&refs).expect("cagra build");
    let cagra_build = t.elapsed().as_secs_f64();
    let (cagra_us, cagra_hits) = timed_search(&cagra, &queries);
    emit(format!(
        "cagra: n={} dim={} build={:.2}s search={:.1}us recall@10={:.4}",
        n,
        DIM,
        cagra_build,
        cagra_us,
        recall_at_k(&cagra_hits, &truth)
    ));

    // HNSW on the CPU, identical data. `HnswIndex::build` inserts
    // sequentially, so at n=1M this is a multi-hour single-threaded run;
    // announce it so a tail of the log distinguishes "still building" from
    // "hung".
    emit(format!("...: n={n} starting hnsw build (single-threaded)"));
    let mut hnsw = HnswIndex::new(DistanceMetric::Euclidean, DIM as u32);
    let t = Instant::now();
    hnsw.build(&refs).expect("hnsw build");
    let hnsw_build = t.elapsed().as_secs_f64();
    let (hnsw_us, hnsw_hits) = timed_search(&hnsw, &queries);
    emit(format!(
        "hnsw:  n={} dim={} build={:.2}s search={:.1}us recall@10={:.4}",
        n,
        DIM,
        hnsw_build,
        hnsw_us,
        recall_at_k(&hnsw_hits, &truth)
    ));
}

#[test]
#[ignore = "requires a GPU and the gpu_cuvs build environment"]
fn bench_100k() {
    run_case(100_000);
}

#[test]
#[ignore = "requires a GPU and the gpu_cuvs build environment"]
fn bench_1m() {
    run_case(1_000_000);
}

//! Tonic transport for Phase D `LogFollower`. The in-process
//! `LocalFollower` from `replication.rs` wraps a `ShardLog`
//! directly; this module ships:
//!
//! - [`TonicLogServer`] — a tonic service that hosts one or more
//!   shard logs and exposes their `LocalFollower`s over gRPC.
//! - [`TonicFollower`] — a `LogFollower` impl that talks to a
//!   remote `TonicLogServer` via gRPC. The `LogWriter` from
//!   replication.rs doesn't care whether followers are local or
//!   remote — same trait.
//!
//! Wire format: each RPC carries a `bytes payload` that's the
//! bincode encoding of the matching Rust struct. Same pattern as
//! veda-coordinator's Raft transport (see
//! `crates/veda-coordinator/proto/raft.proto` for the
//! justification).

use std::collections::HashMap;
use std::sync::Arc;

use async_trait::async_trait;
use tokio::sync::RwLock;
use tonic::{Request, Response, Status};

use crate::replication::{
    AppendAck, AppendRpc, EnsembleError, LocalFollower, LogFollower, NodeId,
};

// Generated by tonic-build into OUT_DIR; the macro re-exports
// the proto types as the `veda::log` module.
pub mod proto {
    tonic::include_proto!("veda.log");
}

pub use proto::veda_log_client::VedaLogClient;
pub use proto::veda_log_server::{VedaLog, VedaLogServer};
use proto::RawRpc;

/// Wire payload for `FenceTo`. Mirrors `LogFollower::fence_to`.
#[derive(Debug, serde::Serialize, serde::Deserialize)]
pub struct FenceRpc {
    pub epoch: u64,
}

/// Wire payload for `LastDurableSeq` (no inputs; an empty
/// marker for symmetry with the other RPCs).
#[derive(Debug, serde::Serialize, serde::Deserialize)]
pub struct LastDurableRpc {}

/// Server-side: maps `(shard_id) → LocalFollower`. One service
/// instance can host any number of shards.
pub struct TonicLogService {
    followers: Arc<RwLock<HashMap<String, Arc<LocalFollower>>>>,
}

impl Default for TonicLogService {
    fn default() -> Self {
        Self::new()
    }
}

impl TonicLogService {
    pub fn new() -> Self {
        Self {
            followers: Arc::new(RwLock::new(HashMap::new())),
        }
    }

    /// Register a shard's follower under `shard_id`. Subsequent
    /// RPCs that carry the same shard_id route here.
    pub async fn register(&self, shard_id: impl Into<String>, follower: Arc<LocalFollower>) {
        self.followers.write().await.insert(shard_id.into(), follower);
    }

    async fn route(&self, shard_id: &str) -> Result<Arc<LocalFollower>, Status> {
        self.followers
            .read()
            .await
            .get(shard_id)
            .cloned()
            .ok_or_else(|| Status::not_found(format!("shard_id {shard_id} not hosted")))
    }
}

/// What every RPC carries: `(shard_id, payload_bincode)`.
#[derive(Debug, serde::Serialize, serde::Deserialize)]
pub struct ShardEnvelope<T> {
    pub shard_id: String,
    pub payload: T,
}

#[async_trait]
impl VedaLog for TonicLogService {
    async fn append(
        &self,
        req: Request<RawRpc>,
    ) -> Result<Response<RawRpc>, Status> {
        let env: ShardEnvelope<AppendRpc> = bincode::deserialize(&req.into_inner().payload)
            .map_err(|e| Status::invalid_argument(format!("decode AppendRpc: {e}")))?;
        let follower = self.route(&env.shard_id).await?;
        let ack = follower
            .append(env.payload)
            .await
            .map_err(|e| Status::internal(format!("follower.append: {e}")))?;
        let payload = bincode::serialize(&ack)
            .map_err(|e| Status::internal(format!("encode AppendAck: {e}")))?;
        Ok(Response::new(RawRpc { payload }))
    }

    async fn last_durable_seq(
        &self,
        req: Request<RawRpc>,
    ) -> Result<Response<RawRpc>, Status> {
        let env: ShardEnvelope<LastDurableRpc> = bincode::deserialize(&req.into_inner().payload)
            .map_err(|e| Status::invalid_argument(format!("decode LastDurableRpc: {e}")))?;
        let follower = self.route(&env.shard_id).await?;
        let seq = follower
            .last_durable_seq()
            .await
            .map_err(|e| Status::internal(format!("follower.last_durable_seq: {e}")))?;
        let payload = bincode::serialize(&seq)
            .map_err(|e| Status::internal(format!("encode u64: {e}")))?;
        Ok(Response::new(RawRpc { payload }))
    }

    async fn fence_to(
        &self,
        req: Request<RawRpc>,
    ) -> Result<Response<RawRpc>, Status> {
        let env: ShardEnvelope<FenceRpc> = bincode::deserialize(&req.into_inner().payload)
            .map_err(|e| Status::invalid_argument(format!("decode FenceRpc: {e}")))?;
        let follower = self.route(&env.shard_id).await?;
        follower
            .fence_to(env.payload.epoch)
            .await
            .map_err(|e| Status::internal(format!("follower.fence_to: {e}")))?;
        let payload = bincode::serialize(&())
            .map_err(|e| Status::internal(format!("encode (): {e}")))?;
        Ok(Response::new(RawRpc { payload }))
    }
}

/// Client-side `LogFollower` that proxies to a remote
/// `TonicLogService`.
pub struct TonicFollower {
    node_id: NodeId,
    shard_id: String,
    client: tokio::sync::Mutex<VedaLogClient<tonic::transport::Channel>>,
}

impl TonicFollower {
    /// Build by dialling `endpoint` (e.g. `http://10.0.0.7:6342`).
    pub async fn connect(
        node_id: NodeId,
        shard_id: impl Into<String>,
        endpoint: impl Into<String>,
    ) -> Result<Self, EnsembleError> {
        let ep = endpoint.into();
        let channel = tonic::transport::Endpoint::from_shared(ep.clone())
            .map_err(|e| EnsembleError::Transport(format!("endpoint: {e}")))?
            .connect()
            .await
            .map_err(|e| EnsembleError::Transport(format!("dial {ep}: {e}")))?;
        let client = VedaLogClient::new(channel);
        Ok(Self {
            node_id,
            shard_id: shard_id.into(),
            client: tokio::sync::Mutex::new(client),
        })
    }

    /// Build from a pre-existing `tonic::transport::Channel` —
    /// useful when the caller pools channels across many
    /// followers.
    pub fn from_channel(
        node_id: NodeId,
        shard_id: impl Into<String>,
        channel: tonic::transport::Channel,
    ) -> Self {
        Self {
            node_id,
            shard_id: shard_id.into(),
            client: tokio::sync::Mutex::new(VedaLogClient::new(channel)),
        }
    }

    #[tracing::instrument(
        name = "log_replication_rpc",
        skip(self, which, payload),
        fields(shard_id = %self.shard_id)
    )]
    async fn rpc<T: serde::Serialize, R: for<'de> serde::Deserialize<'de>>(
        &self,
        which: RpcKind,
        payload: T,
    ) -> Result<R, EnsembleError> {
        let env = ShardEnvelope {
            shard_id: self.shard_id.clone(),
            payload,
        };
        let bytes = bincode::serialize(&env)
            .map_err(|e| EnsembleError::Transport(format!("encode: {e}")))?;
        let mut client = self.client.lock().await;
        let req = Request::new(RawRpc { payload: bytes });
        let resp = match which {
            RpcKind::Append => client.append(req).await,
            RpcKind::LastDurable => client.last_durable_seq(req).await,
            RpcKind::FenceTo => client.fence_to(req).await,
        }
        .map_err(|e| EnsembleError::Transport(format!("rpc: {e}")))?;
        let resp_bytes = resp.into_inner().payload;
        bincode::deserialize(&resp_bytes)
            .map_err(|e| EnsembleError::Transport(format!("decode: {e}")))
    }
}

enum RpcKind {
    Append,
    LastDurable,
    FenceTo,
}

#[async_trait]
impl LogFollower for TonicFollower {
    fn node_id(&self) -> NodeId {
        self.node_id
    }

    async fn append(&self, rpc: AppendRpc) -> Result<AppendAck, EnsembleError> {
        self.rpc(RpcKind::Append, rpc).await
    }

    async fn last_durable_seq(&self) -> Result<u64, EnsembleError> {
        self.rpc(RpcKind::LastDurable, LastDurableRpc {}).await
    }

    async fn fence_to(&self, epoch: u64) -> Result<(), EnsembleError> {
        let _: () = self.rpc(RpcKind::FenceTo, FenceRpc { epoch }).await?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::format::{LogEntryV2, LogOp};
    use crate::replication::LogEnsemble;
    use crate::shard_log::ShardLog;
    use bytes::Bytes;
    use std::time::Duration;
    use veda_time::Hlc;

    /// Spin up a `TonicLogService` on a random port, register
    /// one shard, then connect a `TonicFollower` to it and run
    /// the full LogFollower contract.
    #[tokio::test]
    async fn tonic_follower_round_trips_against_real_server() {
        let tmp = tempfile::tempdir().unwrap();
        let log = Arc::new(ShardLog::open(tmp.path()).unwrap());
        let local = Arc::new(LocalFollower::new(7, log));
        let svc = TonicLogService::new();
        svc.register("docs:0", local.clone()).await;

        // Bind to a random port.
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        let incoming = tokio_stream::wrappers::TcpListenerStream::new(listener);
        let server = tonic::transport::Server::builder()
            .add_service(VedaLogServer::new(svc))
            .serve_with_incoming(incoming);
        let _handle = tokio::spawn(server);
        // Give the server a tick to start listening.
        tokio::time::sleep(Duration::from_millis(50)).await;

        let follower = TonicFollower::connect(
            7,
            "docs:0",
            format!("http://{addr}"),
        )
        .await
        .unwrap();

        // last_durable_seq is 0 on a fresh shard.
        let s0 = follower.last_durable_seq().await.unwrap();
        assert_eq!(s0, 0);

        // Append one entry.
        let entry = LogEntryV2 {
            seq_id: 1,
            hlc_ts: Hlc::new(1, 0),
            epoch: 1,
            key: Bytes::from_static(b"k"),
            op: LogOp::Put,
            payload: Bytes::from_static(b"v"),
        };
        let rpc = AppendRpc {
            epoch: 1,
            entries: vec![entry],
        };
        let ack = follower.append(rpc).await.unwrap();
        match ack {
            AppendAck::Acked { last_durable_seq } => assert_eq!(last_durable_seq, 1),
            AppendAck::Fenced { .. } => panic!("unexpected fence"),
        }

        // last_durable_seq advances.
        let s1 = follower.last_durable_seq().await.unwrap();
        assert_eq!(s1, 1);

        // fence_to moves the follower forward.
        follower.fence_to(5).await.unwrap();
        // Old-epoch append must fence.
        let stale = AppendRpc {
            epoch: 2,
            entries: vec![LogEntryV2 {
                seq_id: 2,
                hlc_ts: Hlc::new(2, 0),
                epoch: 2,
                key: Bytes::from_static(b"k"),
                op: LogOp::Put,
                payload: Bytes::from_static(b"v2"),
            }],
        };
        let ack = follower.append(stale).await.unwrap();
        match ack {
            AppendAck::Fenced { current_epoch } => assert!(current_epoch >= 5),
            AppendAck::Acked { .. } => panic!("stale-epoch append must fence"),
        }
    }

    /// Multi-follower writer where one follower is local and one
    /// is a Tonic remote. Pins that the `LogFollower` trait does
    /// abstract the transport.
    #[tokio::test]
    async fn writer_with_mixed_local_and_tonic_followers() {
        // Local follower 1.
        let tmp1 = tempfile::tempdir().unwrap();
        let log1 = Arc::new(ShardLog::open(tmp1.path()).unwrap());
        let local1: Arc<dyn LogFollower> = Arc::new(LocalFollower::new(1, log1));

        // Tonic-served follower 2.
        let tmp2 = tempfile::tempdir().unwrap();
        let log2 = Arc::new(ShardLog::open(tmp2.path()).unwrap());
        let local2 = Arc::new(LocalFollower::new(2, log2));
        let svc = TonicLogService::new();
        svc.register("col:0", local2.clone()).await;

        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        let incoming = tokio_stream::wrappers::TcpListenerStream::new(listener);
        let server = tonic::transport::Server::builder()
            .add_service(VedaLogServer::new(svc))
            .serve_with_incoming(incoming);
        let _handle = tokio::spawn(server);
        tokio::time::sleep(Duration::from_millis(50)).await;
        let remote2: Arc<dyn LogFollower> = Arc::new(
            TonicFollower::connect(2, "col:0", format!("http://{addr}"))
                .await
                .unwrap(),
        );

        let ensemble = LogEnsemble::new(vec![1, 2], 2, 1, 1);
        let writer = crate::replication::LogWriter::new(ensemble, vec![local1, remote2]);
        let entries: Vec<LogEntryV2> = (1..=3)
            .map(|i| LogEntryV2 {
                seq_id: i,
                hlc_ts: Hlc::new(i, 0),
                epoch: 1,
                key: Bytes::copy_from_slice(&i.to_le_bytes()),
                op: LogOp::Put,
                payload: Bytes::from(format!("v{i}").into_bytes()),
            })
            .collect();
        let last = writer.append_batch(entries).await.unwrap();
        assert!(last >= 3, "expected ≥3 durable, got {last}");
    }
}
